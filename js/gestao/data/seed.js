import { currentYearMonth, getWeekdayShortPT } from '../core/formatters.js';

function buildSampleAttendance(ym, employeeIds) {
  const attendance = {};
  const today = new Date();
  const [y, m] = ym.split('-').map(Number);
  const maxDay =
    today.getFullYear() === y && today.getMonth() + 1 === m
      ? Math.min(today.getDate(), 22)
      : 20;

  employeeIds.forEach((empId, idx) => {
    attendance[empId] = {};
    for (let d = 1; d <= maxDay; d += 1) {
      const wd = getWeekdayShortPT(ym, d);
      if (wd === 0 || wd === 6) continue;
      const dateStr = `${ym}-${String(d).padStart(2, '0')}`;
      if (idx === 1 && d === 9) {
        attendance[empId][dateStr] = { status: 'FJ', note: 'Consulta médica (atestado)' };
      } else if (idx === 3 && d === 11) {
        attendance[empId][dateStr] = { status: 'FI', note: 'Ausência sem justificação prévia' };
      } else if (idx === 4 && (d === 16 || d === 17)) {
        attendance[empId][dateStr] = { status: 'FE', note: 'Dias de férias aprovados' };
      } else {
        attendance[empId][dateStr] = { status: 'P', note: '' };
      }
    }
  });

  return attendance;
}

